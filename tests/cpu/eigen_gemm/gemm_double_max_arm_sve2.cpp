/* No Eigen types in this TU: the payload lives in the per-tier body TUs
 * (gemm_double_max_arm_body.cpp), compiled once per vector length under
 * their own Eigen namespaces — design §4.7. */

/* Memory-safe dimension bounds: joint-solver lo/hi AND knob clamp.
 * 全部可通过统一配置层覆盖: -O eigen_gemm_double_max_arm_sve2.mdim=N /
 * 配置文件 / 环境变量, 见 sdc_stress_config.h。 */
#define MDIM_MIN 1024
#define MDIM_MAX 4096

/* Tier recorded at init (from the framework-pinned control thread, whose
 * VL the init aux thread inherits): the joint-solver probe dispatches on
 * it, so the fixed-width packets it executes always match the executing
 * VL. The GEMM payload's matrices are tier-agnostic memory (plain double
 * arrays), so — unlike the SVE SVD pair, where make_data allocates
 * Eigen objects per tier — a worker/run tier divergence would be a
 * sizing-accuracy concern, not a cross-tier reinterpretation hazard;
 * test_run therefore keeps dispatching on the worker's OWN readback
 * (unchanged semantics, no new failure mode). [2026-11-02 unification
 * update: the shared dispatcher run (EIGEN_SVE_DEFINE_DISPATCHERS in
 * sandstone_eigen_sve_dispatch.h) now FAILS that divergence anyway —
 * fail-closed hardening per the framework arm64 spec policy, applied
 * uniformly across every Eigen SVE test; a tier-agnostic payload can
 * never be harmed by the stricter check, and a genuinely diverging
 * environment is a bug to surface, not paper over.]
 *
 * The dimension chosen at init (knob/env > joint solver) used to live in
 * the file-static gemm_run_dim read by every worker of this child; it
 * now lives in per-child test->data (gemm_sve_data in the body TU, read
 * back by run_body) — the per-child derivation the T6 child-side sizing
 * already gave us (each exec_each_test child re-solves its own dimension),
 * now carried in the data pointer the framework owns instead of a
 * TU-local static.
 * Both the gemm_sve2_tier_bits variable and the joint-solver probe routing
 * (gemm_sve2_solve_once: same pattern as the SVE SVD pair's solve probe) are
 * generated by EIGEN_SVE_DEFINE_DISPATCHERS below (migrated there
 * 2026-11-02; semantics preserved verbatim). */
EIGEN_SVE_DECLARE_BODY_NS(gemm_sve2);
EIGEN_SVE_DEFINE_DISPATCHERS(gemm_sve2);

/*
 * preinit (runs once in the PARENT, before run_one_test computes
 * test_duration() — so writing test->desired_duration here is effective
 * for the very first run, unlike in test_init; same pattern as
 * ist_skip_preinit setting test->minimum_duration).
 *
 * T6 (spec §4.5 q2 invariant, mirror of the P0-1 SVD fix): the dimension
 * itself is no longer sized here — the child's test_init does that per
 * NUMA node with the joint solver, which also fixes exec_each_test
 * children (their freshly-exec'd image never ran this preinit, so the
 * old parent-sized static arrived un-initialised at 1024). The preinit
 * only writes an UPPER bound:
 *
 *   n_hi = sqrt(budget650_kb / (workers × c_GEMM_F64)), clamped to
 *          [MDIM_MIN, MDIM_MAX] — the same four-source memory budget
 *          and RSS-table coefficient the child's n_mem uses, with
 *          workers = the run's actual whole-machine worker count
 *          (sdc_total_threads(), available in preinit: commit_shmem()
 *          runs before test_preinit). That aligns the DENOMINATOR —
 *          the worker scale, whose misalignment was the old 127
 *          hardcode bug (child n up to sqrt(127/workers) above n_hi
 *          on sub-127-worker hosts). The full child-side relation
 *          (issue #536: the earlier "n_hi tracks it on every host
 *          class" overclaimed — the folding argument covers the
 *          worker scale only) is
 *              n_mem = n_hi × sqrt(memshare / cpushare),
 *          because the child's node budget is the same budget
 *          weighted by the node's MemFree/ΣMemFree share while its
 *          node_threads is the node's CPU share × the same worker
 *          count (sdc_numa.cpp weights, sdc_joint_dim_slice folds
 *          workers/total_cpus into node_cpus; zero-memory nodes fold
 *          their CPUs into the fallback node). n_mem == n_hi only
 *          where the shares match: single-memory-node hosts (both
 *          shares 1 — the reference class — exact) and MemFree/CPU-
 *          balanced NUMA (approximate). Off that domain TWO bounded
 *          mechanisms push n above n_hi, each eroding the
 *          5×dur+30 s timeout margin by (n/n_hi)³ — for GEMM it
 *          stacked on this host class' own AR understatement pre-#506
 *          (table 5 vs ~15 measured, see the init comment's
 *          re-calibration record; #506 closed that leg — the remaining
 *          arithmetic is in the timeout paragraph below):
 *            - MemFree-rich node: 75% of free memory on 50% of the
 *              CPUs → n ≈ 1.22× n_hi → dur under-estimates the real
 *              iteration ~1.8×.
 *            - VmHWM feedback adopting a lower c (outside the 15%
 *              deadzone, 0.7× table-anchor floor in
 *              sdc_stress_config.h): n up to 1/sqrt(0.7) ≈ 1.2× even
 *              on balanced hosts — designed (OOM-bounded) and
 *              structurally invisible to this preinit, which runs
 *              before any child VmHWM exists and never rewrites.
 *          Deliberately NOT clamped (n = min(n_mem, n_hi)): the
 *          clamp's "never fires on balanced topologies" premise is
 *          false — it would cancel the designed feedback inflation
 *          on every host where feedback adopts, under-stress
 *          MemFree-rich nodes, and still miss the reverse imbalance
 *          (memshare < cpushare → n < n_hi → dur OVER-estimates →
 *          un-budgeted extra iterations, the do-while mode described
 *          below). Belts that remain: n_run (min(n_mem, n_run) pins
 *          the real iteration to the 200 s calibration wherever time
 *          binds first) and the 5× timeout factor absorbing the
 *          model's own error.
 *   dur  = AR(compute) × 2 × t(n_hi) × 0.95,  t(N) = T1024·(N/1024)³ s
 *          (quiet single-probe power law, two-point differential fit —
 *          see the measurement record below). The explicit knob tier
 *          models dur = ar × 2 × t(knob) × 0.95 with ar = the same
 *          compute-family table value, EXCEPT workers == 1 takes ar = 1
 *          (the table value is a FULL-CORE figure; a lone worker contends
 *          only with itself — PR#384 review, id 4439402781), and ALSO
 *          writes minimum_duration = ar × 2 × t(knob) (no 0.95 margin:
 *          the "at least one full iteration" floor), because the
 *          framework-level -t override replaces desired_duration
 *          unconditionally and would otherwise land the explicit tier on
 *          the 300 s hard grace (PR#384 review, id 4439402765).
 *
 * The AR × 2 mirrors the joint solver's run_budget semantics (fill + one
 * solve per iteration, all-core slowdown factor), so dur models the
 * FULL-CORE single-iteration time at the memory ceiling, and the ×0.95
 * margin sits dur 5% BELOW that model (issue #479: this sentence, and the
 * DECLARE_TEST comment below, previously stated the direction backwards).
 * The run-side do-while — do … while (test_time_condition()), which
 * CONTINUES while the deadline has not expired — executes exactly one
 * iteration only when dur is at or BELOW the child's real single-iteration
 * time: the deadline is then already expired when iteration #1 finishes,
 * which is what the −5% margin is for; a dur above the real time would
 * instead start a second, un-budgeted iteration. On this host class dur
 * sits on that side twice over: the −5% margin, plus (pre-#506) the table
 * AR (5) understating the measured all-core slowdown (~15) — dur ≈ 42 s
 * vs the ~55-60 s measured multiply; the #506 re-calibration (comp 5→15)
 * closes that gap. The derived
 * timeout test_timeout() = 5×duration + 30 s (300 s floor) needs the
 * OTHER relation — real iteration <= timeout — and that holds only
 * within the model-error budget: child n <= n_hi on the reference
 * class, but the two mechanisms in the n_hi bullet above (issue #536)
 * push n above it (MemFree/CPU share imbalance up to sqrt(share ratio)
 * ×, feedback adoption up to 1.2×), and each (n/n_hi)³ of inflation
 * eats the 5× factor directly. The #506 re-calibration removed the
 * old stacking (the compute-table value IS the measured ~15 now), so
 * (n/n_hi)³ = 4.75 exhausts the factor at n/n_hi ≈ 1.68 — a ≈2.8×
 * MemFree/CPU share imbalance alone, or ≈2.0× stacked with the 1.2×
 * feedback adoption (SIGQUIT mid-iteration — the P0 mode, now
 * reachable from the sizing side as well; pre-#506, with the 3×
 * table understatement, the same kill needed only ≈1.4×). The belt
 * that remains is n_run (min(n_mem, n_run) pins the real iteration
 * to the 200 s calibration wherever time binds first); on this host
 * class memory binds first (n_mem=3364 < n_run~4900), so the
 * imbalance exposure is live here.
 * EXCEPT for an explicit knob/env, which the child applies VERBATIM
 * (dim = knob, no min against n_hi, issue #352 mirror of the SVD fix):
 * the duration model must follow the knob too, or any knob above n_hi
 * times out at the 300 s hard grace and the child is SIGQUIT-killed
 * mid-iteration.
 * (Correction of an earlier comment that claimed
 * a host with fewer threads "only shrinks n_hi — the safe direction":
 * that was backwards. A hard-coded 127 makes the child's n_mem
 * denominator SMALLER than n_hi's on sub-127-worker hosts, so child n
 * can EXCEED n_hi by up to sqrt(127/workers) — dur then UNDER-estimates
 * the real iteration (cubic: ~2.8× at 64 workers) and the derived
 * timeout loses its headroom, the UNSAFE direction. Using the actual
 * worker count restores the invariant's worker-scale leg on every
 * host; the MemFree/CPU-share leg (n_hi bullet above) is what still
 * gates it — issue #536. The child's own n_run still bounds one
 * iteration at 200 s as a second belt.)
 *
 * T1024 measurement record (2026-10-28, this host, 256-bit tier — the
 * joint solver's own [时间校准] probes on the quiet single-slice -n 1
 * run: 1024→119.2 ms, 2048→1001.2 ms, verification 4096→7772.5 ms.
 * Cubic differential of the probe pair: a = 882 ms / (2048³−1024³) ⇒
 * T1024 = 0.1260 s; the 4096 point back-solves to 0.1214 s (−3.7%,
 * consistency check). Measured exponent k = 3.07, so the cubic model
 * sits ~9% below the measured power at the n_hi ceiling — well inside
 * the ×2 contract margin above): hosts with a different tier or core
 * count deviate, but only in the safe direction above.
 */
#define GEMM_T1024_S 0.1260    /* quiet fill+multiply at N=1024, seconds */
/* 【#506 退役记录】PR#384 检视 R3 (意见 4440012669) 曾以
 * GEMM_AR_CAVEAT_X=3.0 给显式档 anti-kill 地板(min)的全核 AR 加权,
 * 补 compute 族表值 5.0 对天花板足迹 GEMM 的 3× 实测低估(有效
 * AR≈15)。#506 把表行重标定为 15 后该补偿数值上恒等(5×3=15)且
 * 双重计入, 已删除——min 直接取表 AR 口径, 语义不变。 */

static int eigen_gemm_double_max_arm_sve2_preinit(struct test *test)
{
    /* 静态表 c + 实际全机 worker 数推 n 上界, 再按 AR×2×t(N) 推 duration
     * 上界: child 精算 n 在节点 MemFree/CPU 份额匹配且 VmHWM 反馈未采信
     * 的拓扑上 <= 此上界(spec §4.5; 两机制可使其有界超出——失衡 NUMA
     * 至 sqrt(份额比)×、反馈采信至 1.2×——完整口径与失效边界见上方
     * n_hi bullet, issue #536)。worker 数用
     * sdc_total_threads()(preinit 时 commit_shmem 已初始化, -n/--cpuset
     * 下是请求的 worker 数)而非参考机 127——子进程 n_mem 分母是同一
     * worker 口径(折算到节点), 硬编码 127 在 worker<127 主机上使
     * child n 可超 n_hi 达 √(127/workers), dur 低估真实迭代(不安全向)。 */
    double budget_kb = (double)sdc_budget_bytes(650) / 1024.0;
    /* GEMM_F64 表值引用表函数而非字面量(09c94fc6 遗留项收口): T9 重标定
     * 0.0290→0.0315 后字面量静默陈旧; 引用后 n_hi 随 1/sqrt(c) 收缩 ~4%,
     * 上界性质不变且更紧(child 同表同预算精算, node0-only 时恰等)。 */
    double c_kb = sdc_rss_table_c(SDC_RSS_GEMM_F64);
    int workers = sdc_total_threads();
    if (workers < 1)
        workers = 1;
    /* 防御(issue #489, 与 svd_cdouble_sve 同型守卫 b249c97c): 表函数以 0 为
     * "无表/越界"哨兵(联合求解 sdc_joint_dim_slice 同语义), 无守卫则
     * budget_kb/(workers×0.0) = +inf, (int)inf 是 UB([conv.fpint])。退守
     * 字面量取当前实测表值口径——表重标定时会陈旧(0.0290→0.0315 即例),
     * 但仅此异常路径受影响, 健康表路径 n_hi 逐值不变。 */
    if (c_kb <= 0.0)
        c_kb = 0.0315;
    int n_hi = (int)std::sqrt(budget_kb / ((double)workers * c_kb));
    if (n_hi > MDIM_MAX) n_hi = MDIM_MAX;
    if (n_hi < MDIM_MIN) n_hi = MDIM_MIN;

    /* 显式 knob/env 档(issue #352, 与 SVD 修复同构): child 对显式 mdim
     * 逐字采用(dim = knob, 不与 n_hi 取 min), duration 模型必须跟着
     * knob 缩放, 否则 knob > n_hi 的显式档落在 300 s 硬宽限被 SIGQUIT
     * 误杀。读取通道经 sdc_knob_or_env_clamped 单一实现, 与 child 恒
     * 相同(PR#384 检视, 意见 4432271425: 此前 preinit+child 四份逐字
     * 拷贝纯靠手工同步, 任一侧单独改动即静默重开误杀窗口)。 */
    int64_t knob = sdc_knob_or_env_clamped(test, "mdim", MDIM_MIN, MDIM_MAX);

    double iter_s;
    if (knob > 0) {
        /* 【PR#384 检视, 意见 4439402781】显式档 workers==1 时 ar 取 1——
         * 与 svd_cdouble_sve(f23e2fd9)同构: AR 表值是全核口径, 单 worker
         * 自争抢为 1(物理定义); 不折算则 -n 1 显式档裸跑 target 被拉到
         * ~ar 倍 t(knob)(GEMM_T1024_S 本身是 quiet -n 1 口径, 本机单节点
         * compute 表值 #506 后为 15 → ~14.3 次迭代; 旧表 5.0 时 4.76),
         * 标准 -t…-n 1 回归路径的单迭代
         * 语义破坏。auto 分支维持 f6783077 原模型(ar×2×t(n_hi) 不随
         * worker 数折算: 表值 ar 在 -n 1 下只虚抬 desired——有 -t 时被
         * 框架层覆盖, 无 -t 时 target 与 5×target+30 宽限同涨、单迭代
         * 时长由 child 侧联合求解的 n(#563 起 -n 1 档 ar=1)决定, 只多
         * 跑迭代不膨胀单迭代; 原注释「与联合求解 per_solve 同一口径」
         * 的论据随 #563 闸门失准, 依上述自有理由成立)。 */
        double ar = workers > 1
                ? sdc_ar_factor(SDC_FAM_COMPUTE_BOUND, sdc_numa_probe()) : 1.0;
        iter_s = ar * 2.0 * GEMM_T1024_S * std::pow((double)knob / 1024.0, 3.0);
        /* 【PR#384 检视, 意见 4439402765】显式档兼写 minimum_duration——
         * 与 svd_cdouble_sve(9a82f53b)同构: -t 在框架层无条件覆盖
         * desired_duration(sandstone_run.cpp test_duration), 无 min 夹钳时
         * `-t 2000 -O …mdim=<大>` 的 timeout 落 300s floor, 而全核单迭代
         * = 有效AR×2×t(knob)——pre-#506 表值 5.0 在大足迹下实测低估
         * 3×(有效 AR≈15, 甚至 '~600s' host class), mdim=4096 全核单迭代
         * ≈242s(计入立方模型 -9% 低估 ≈264s), 余量不足 20%, 表值档
         * host class 上确定性 SIGQUIT。min=单次全迭代模型(无 0.95
         * 裕量), -t 小值档 target 被夹钳到单迭代, timeout
         * (5×min+30)随之随 knob 缩放。auto 分支不写: auto 单迭代由
         * run_budget=200s×AR 表值设计收在 300s floor 内(本 host class
         * 内存侧先绑住, n_run 非绑定侧)。
         * 【PR#384 检视 R3, 意见 4440012669; #506 表重标定后改述】min 的
         * 全核口径曾再乘 CAVEAT 低估系数(GEMM_AR_CAVEAT_X=3×, 已退役):
         * 仅表值口径的 min 裕量只有 433s/264s≈1.6×(mdim=4096 全核 -t
         * 小值档), 而 GEMM_T1024_S 系本机 256-bit quiet 定标——VL=128
         * 档实测每迭代慢 1.78×(2026-11-02, -n 1 -O mdim=2048: 每内层
         * 迭代 1.757s→3.133s), 与有效 AR≈15 叠加后旧 kill 阈值
         * 5×ar_table=25 被 15×1.78=26.7 打穿(计入 T1024 立方模型 -9%
         * 低估更甚)。#506 把 compute 表值重标定为实测上界 15 后, min
         * = 表值口径×2×t(knob) 即最坏真实单迭代(数值与旧 5×3 恒等),
         * VL=128 叠加最坏仍有 5×15/(15×1.78)≈2.8× 裕量(计入 -9%
         * ≈2.5×)——账目数值不变, 构成自 CAVEAT 加权改为表值直取。
         * workers==1 不折算(意见 4439402781, 上方): 表值是全核口径,
         * -n 1 显式档单迭代语义保持; desired 维持表值标称口径(时间
         * 预算目标, 非反 kill 地板)。SVD 侧对照: 其 mem 族表值已 #506
         * 重标定为 40(实测最坏 child AR≈39-40 取上界), 裕量
         * 5×40/(39×1.064×1.02)≈4.73×, 无需任何额外加权。中间 worker 档
         * (1<w<全核) min 随之更保守——二值闸门裁定见意见 4439402800/
         * 4440012653(保守方向, 插值无标定数据反开 kill 窗)。 */
        test->minimum_duration = (int)(iter_s * 1000.0);   /* ms */
    } else {
        double ar = sdc_ar_factor(SDC_FAM_COMPUTE_BOUND, sdc_numa_probe());
        iter_s = ar * 2.0 * GEMM_T1024_S * std::pow((double)n_hi / 1024.0, 3.0);
    }
    /* 【PR#384 检视 R5, 意见 4463650400】显式档生效侧澄清: 本 desired
     * (0.95×iter_s)恒小于上方 min(1.0×iter_s ≈ 1.05×desired),
     * 而框架 test_duration 的 min 夹钳最后执行
     * (sandstone_run.cpp:1879-1880)→ 显式档的 target/timeout 恒由
     * min 决定, 本 desired 在显式档是模型记录值(表值标称口径的时间
     * 预算目标, 见意见 4440012669 裁定), 单独调它不改显式档时长(须调
     * min)。auto 档不写 min, desired 才是生效目标——两档共用本行,
     * "-5% margin" 仅对 auto 档是真实生效裕量。 */
    test->desired_duration = (int)(iter_s * 1000.0 * 0.95);   /* ms */
    return EXIT_SUCCESS;
}

/* All-VL Phase 2 P5: framework-layer capability + 128..1024-bit range
 * gate (framework/device/cpu/arm64/arm64_vl.h). The HWCAP/rdvl probe
 * executes no SVE instruction, and this TU has SVE instructions baked
 * in, so a clean skip must be reachable before any of them; the
 * framework's compiler_minimum_device gate already skips non-SVE hosts
 * before init — this keeps a test-specific reason if that ordering ever
 * changes. The GEMM payload itself is VL-agnostic; test_run dispatches to
 * the per-tier variant that matches the worker's pinned VL (design §4.7).
 * T6: after the gate, the child sizes the dimension (knob/env > joint
 * solver) and records the tier the probe must dispatch to. */
static int eigen_gemm_double_max_arm_sve2_init(struct test *test)
{
    if (!arm64_cpu_has_sve2()) {
        log_skip(CpuNotSupportedSkipCategory,
                 "%s: SVE2 required (HWCAP2_SVE2 absent); the SVE2 companion "
                 "runs on SVE2 hardware or gem5 SVE2 emulation — see the "
                 "honest-scope note in this file's header", test->id);
        return EXIT_SKIP;
    }
    const long svl = arm64_require_sve_vl(test, 128, 1024);
    if (svl < 0)
        return EXIT_SKIP;

    /* Framework pinned the control thread before this aux thread was
     * created, so `svl` is the tier the workers run at; the joint
     * solver's probe below executes that tier's fixed-width packets on
     * THIS thread (see gemm_sve2_tier_bits above for the tier/run contract).
     * (gemm_sve2_tier_select: generated by EIGEN_SVE_DEFINE_DISPATCHERS in
     * sandstone_eigen_sve_dispatch.h — the tier whitelist this TU used
     * to spell out by hand.) */
    if (!gemm_sve2_tier_select(test, svl))
        return EXIT_SKIP;

    /* Dimension (T6, spec §4.5): knob > env > joint-solver auto, all in
     * the CHILD so exec_each_test images size themselves. The auto branch
     * probes solve_once on THIS thread (its VL is the tier just recorded)
     * and returns min(n_mem, n_run): per-NUMA-node memory budget against
     * the measured GEMM RSS coefficient, and a full-core single-iteration
     * budget via the power-law fit and the compute-family AR factor.
     * quick mode collapses to MDIM_MIN. run_budget_ms keeps the contract
     * value 200000: on this host class the memory side binds first
     * (n_mem=3364 < n_run~4900-5300), so the time budget is not the
     * sizing constraint. Measurement history (fix round 1 CAVEAT,
     * 2026-10-28): the pre-#506 compute-family AR table entry (5.0; 4.4
     * measured at MEDIUM footprint) UNDERSTATED ceiling-footprint GEMM —
     * the T6 verification run's full-core single multiply at N=3364 took
     * ~55-60 s against a ~4.0 s quiet model, an effective AR of ~15 (3x
     * the table). A host where the time side binds would size n_run for
     * a 200 s iteration that really took ~600 s — past the 300 s hard
     * grace (T5's failure class). #506 re-calibrated the 1-node compute
     * entry to the measured ceiling (15), so the time-bound sizing now
     * lands a real 200 s iteration — the flagged T7/T9 gap is closed at
     * the table root (this comment is the record). */
    int dim;
    int64_t knob = sdc_knob_or_env_clamped(test, "mdim", MDIM_MIN, MDIM_MAX);
    if (knob > 0) {
        dim = (int)knob;
    } else {
        struct sdc_joint_args ja = {
            .lo = MDIM_MIN, .hi = MDIM_MAX,
            .fam = SDC_RSS_GEMM_F64,    /* 0.0315 KB/n²/thread, measured */
            .bytes_per_elem = 8, .matrices_per_thread = 4, .rss_ratio = 6.0,
                    /* legacy triple (pre-table model), ignored while fam
                     * selects the RSS table */
            .shared_bytes_per_slice = 0,   /* init holds no matrices */
            .mem_fraction_permille = 650,
            .ar_fam = SDC_FAM_COMPUTE_BOUND,
            .run_budget_ms = 200000,       /* 全核单迭代预算 (fill+一次乘法×AR) */
        };
        try {
            dim = sdc_joint_dim_slice(test, "mdim", &ja, gemm_sve2_solve_once);
        } catch (...) {
            /* probe allocation failure (transient OOM &c): fall back to
             * the floor — same doctrine as the SVD pair's calibrated path
             * ("上限宁小勿大"): a sizing probe must never terminate the
             * child. */
            log_warning("[联合求解] %s: mdim 探针异常 → 退守下限 %d",
                        test->id, MDIM_MIN);
            dim = MDIM_MIN;
        }
    }
    /* Store the dimension in per-child test->data (was the file-static
     * gemm_run_dim): gemm_sve2_make_data routes to the tier recorded by
     * gemm_sve2_tier_select and the body's run_body reads it back — generated
     * by EIGEN_SVE_DEFINE_DISPATCHERS in sandstone_eigen_sve_dispatch.h. */
    test->data = gemm_sve2_make_data(dim);

    double gb = (double)dim * dim * 8.0 * 4.0 / (1 << 30);
    /* 【PR#384 检视 R5, 意见 4463650411】exec_each_test child 是全新
     * exec 镜像: preinit 只在 parent 跑, 本进程 test 结构两字段恒
     * 静态初值 0——照常打印会被误读为"无下限保护", 而生效的 -t/min
     * 夹钳经 parent 的 test_duration → shmem->current_test_endtime
     * 传入(R3 意见 4440012682 勘误: fork/exec 迭代语义一致)。判据:
     * preinit 成功后 desired_duration 恒 > 0(两分支 iter_s > 0),
     * == 0 即 exec child。 */
    if (test->desired_duration > 0) {
        /* 【PR#384 检视 R6, 意见 4463986196】min 的文案随值走: auto 档
         * 设计不写 min(0 = 无下限, -t/默认时长直接生效), 显式档才有
         * 单迭代下限(#506 起为表 AR 口径, CAVEAT 加权已退役)。 */
        log_info("N=%d (~%.2f GB per thread; sized in child init: knob/env, "
                 "else 联合求解 min(n_mem, n_run); preinit desired_duration "
                 "%d ms, minimum_duration %d ms (%s); "
                 "override with -O eigen_gemm_double_max_arm_sve2.mdim=N)",
                 dim, gb, test->desired_duration, test->minimum_duration,
                 test->minimum_duration > 0
                     ? "显式档: 表 AR 口径单迭代下限, -t 夹钳"
                     : "auto 档: 设计不设下限, -t/默认时长直接生效");
    } else {
        log_info("N=%d (~%.2f GB per thread; sized in child init: knob/env, "
                 "else 联合求解 min(n_mem, n_run); exec_each_test child: "
                 "本进程未跑 preinit, desired/minimum_duration 恒 0——生效的 "
                 "-t/min 夹钳经 parent shmem 传入, 非无下限保护; "
                 "override with -O eigen_gemm_double_max_arm_sve2.mdim=N)",
                 dim, gb);
    }
    return EXIT_SUCCESS;
}

/* Design §4.7 dispatch. The framework already pinned this worker to the
 * chip's highest supported tier (arm64_spec_prepare.h); we read the ACTUAL
 * value back — never the requested one — and pick the variant compiled for
 * it. Re-pinning here is a deliberate idempotent second check: the body's
 * Eigen packets are only correct at their own width, so a silent downgrade
 * of the framework's pin must be caught, not papered over.
 * (gemm_sve2_run: generated by EIGEN_SVE_DEFINE_DISPATCHERS in
 * sandstone_eigen_sve_dispatch.h — the wrapper body migrated there
 * 2026-11-02. Deltas vs this TU's old hand-written wrapper: the log line
 * unified to "Eigen SVE variant = <bits>-bit", and the variant-mismatch
 * FAIL above added — see the gemm_sve2_tier_bits pointer comment.) */
static int eigen_gemm_double_max_arm_sve2_run(struct test *test, int cpu)
{
    return gemm_sve2_run(test, cpu);
}

/* New with the unification (was absent: data was a file-static, reclaimed
 * by process teardown): free the per-child gemm_sve_data. One-line wrapper
 * around the generated gemm_sve2_cleanup (per-tier switch lives in
 * sandstone_eigen_sve_dispatch.h; the generated function returns void). */
static int eigen_gemm_double_max_arm_sve2_cleanup(struct test *test)
{
    gemm_sve2_cleanup(test);
    return EXIT_SUCCESS;
}

